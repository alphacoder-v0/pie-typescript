/** pie: session/mod.rs:25-27 (`trigger_sidecar_path`). */
export function triggerSidecarPath(sessionPath: string): string {
	return withSidecarExtension(sessionPath, "triggers.json");
}

/** pie: session/mod.rs:29-32 (`cron_sidecar_path`). */
export function cronSidecarPath(sessionPath: string): string {
	return withSidecarExtension(sessionPath, "cron.toml");
}

/** pie: session/mod.rs:54-57 (`endpoint_sidecar_path`). */
export function endpointSidecarPath(sessionPath: string): string {
	return withSidecarExtension(sessionPath, "endpoints.json");
}

/**
 * Rust's `Path::with_extension` replaces everything after the *last* dot in the file name.
 * `resolve(sessionPath, "..")` + string split mirrors that without pulling in `path.parse`
 * platform quirks.
 */
function withSidecarExtension(sessionPath: string, newExt: string): string {
	const dir = resolve(sessionPath, "..");
	const fileName = basename(sessionPath);
	const dot = fileName.lastIndexOf(".");
	const stem = dot === -1 ? fileName : fileName.slice(0, dot);
	return join(dir, `${stem}.${newExt}`);
}

/**
 * Enabled/total counts of a session's automation sidecars (cron jobs + dynamic trigger rules).
 * Cron jobs and triggers are session-scoped, so after exiting a session this is the only record
 * that automation exists at all.
 * pie: session/mod.rs:236-242 (`AutomationCounts`).
 */
export interface AutomationCounts {
	cronEnabled: number;
	cronTotal: number;
	triggerEnabled: number;
	triggerTotal: number;
}

function emptyAutomationCounts(): AutomationCounts {
	return { cronEnabled: 0, cronTotal: 0, triggerEnabled: 0, triggerTotal: 0 };
}

/** pie: session/mod.rs:245-247 (`AutomationCounts::is_empty`). */
export function isAutomationCountsEmpty(counts: AutomationCounts): boolean {
	return counts.cronTotal === 0 && counts.triggerTotal === 0;
}

/** pie: session/mod.rs:249-251 (`AutomationCounts::any_enabled`). */
export function automationCountsAnyEnabled(counts: AutomationCounts): boolean {
	return counts.cronEnabled > 0 || counts.triggerEnabled > 0;
}

/**
 * Short badge for session listings: enabled counts ("2 cron, 1 trigger"), or "automation off"
 * when everything present is disabled. `undefined` when there is nothing.
 * pie: session/mod.rs:253-270 (`AutomationCounts::badge`).
 */
export function automationCountsBadge(counts: AutomationCounts): string | undefined {
	if (isAutomationCountsEmpty(counts)) return undefined;
	const parts: string[] = [];
	if (counts.cronEnabled > 0) parts.push(`${counts.cronEnabled} cron`);
	if (counts.triggerEnabled > 0) parts.push(`${counts.triggerEnabled} trigger`);
	if (parts.length === 0) return "automation off";
	return parts.join(", ");
}

/**
 * Oracle's shared `EnabledOnly` sidecar shape -- `struct EnabledOnly { #[serde(default)] enabled:
 * bool }` inside `Vec<EnabledOnly>`, itself `#[serde(default)]`. Reproduces serde's strictness,
 * which is *not* the same as a lenient field-by-field read:
 *   - list key absent          -> empty list (the field-level `#[serde(default)]`)
 *   - list key present, not a sequence of tables/objects -> deserialization error
 *   - element `enabled` absent -> false (the field-level `#[serde(default)]`)
 *   - element `enabled` present with the wrong type (e.g. the string "true") -> error
 *   - unknown extra keys       -> ignored (no `deny_unknown_fields`)
 * A deserialization error fails the *whole file*, and oracle's `if let Ok(file)` then leaves the
 * counts at zero -- i.e. no badge at all, not a "disabled" badge. Returns `undefined` for the
 * error case so callers can leave their counts untouched.
 * pie: crates/coding-agent/src/session/mod.rs:275-279, 295-308.
 */
function parseEnabledOnlyList(value: unknown): boolean[] | undefined {
	if (value === undefined) return [];
	if (!Array.isArray(value)) return undefined;
	const enabled: boolean[] = [];
	for (const item of value) {
		if (typeof item !== "object" || item === null || Array.isArray(item)) return undefined;
		const raw = (item as { enabled?: unknown }).enabled;
		if (raw === undefined) {
			enabled.push(false);
			continue;
		}
		if (typeof raw !== "boolean") return undefined;
		enabled.push(raw);
	}
	return enabled;
}

/**
 * Count automation in the sidecars next to `sessionPath`. Missing or unparsable sidecar files
 * degrade to zero counts -- this feeds listings and hints, never hard errors. "Unparsable" here
 * follows oracle's serde contract, not just syntactic validity: see `parseEnabledOnlyList`.
 * pie: session/mod.rs:295-310 (`automation_counts`).
 */
export async function automationCounts(sessionPath: string): Promise<AutomationCounts> {
	const counts = emptyAutomationCounts();
	try {
		const text = await readFile(cronSidecarPath(sessionPath), "utf8");
		const parsed = parseToml(text) as { jobs?: unknown };
		const jobs = parseEnabledOnlyList(parsed.jobs);
		if (jobs) {
			counts.cronTotal = jobs.length;
			counts.cronEnabled = jobs.filter((enabled) => enabled).length;
		}
	} catch {
		// missing file or corrupt toml -- degrade to zero, matching oracle's `if let Ok(...)`.
	}
	try {
		const text = await readFile(triggerSidecarPath(sessionPath), "utf8");
		const parsed = JSON.parse(text) as { rules?: unknown };
		const rules = parseEnabledOnlyList(parsed.rules);
		if (rules) {
			counts.triggerTotal = rules.length;
			counts.triggerEnabled = rules.filter((enabled) => enabled).length;
		}
	} catch {
		// same degrade-to-zero contract.
	}
	return counts;
}

async function listSessionFilesSorted(dir: string): Promise<string[]> {
	try {
		const names = await readdir(dir);
		return names
			.filter((f) => f.endsWith(".jsonl"))
			.map((f) => join(dir, f))
			.sort();
	} catch {
		return [];
	}
}

function listSessionFilesSortedSync(dir: string): string[] {
	try {
		return readdirSync(dir)
			.filter((f) => f.endsWith(".jsonl"))
			.map((f) => join(dir, f))
			.sort();
	} catch {
		return [];
	}
}

/** Header-only read (bounded buffer) -- never parses the body, so no salvage/throw decision. */
function readSessionHeaderSync(path: string): SessionHeader | null {
	try {
		const fd = openSync(path, "r");
		const buffer = Buffer.alloc(4096);
		const bytesRead = readSync(fd, buffer, 0, 4096, 0);
		closeSync(fd);
		const firstLine = buffer.toString("utf8", 0, bytesRead).split("\n")[0];
		if (!firstLine) return null;
		return parseSessionHeaderLine(firstLine);
	} catch {
		return null;
	}
}

/**
 * Resolve a session id (full uuidv7 or unique prefix) to its transcript path within `dir`. Falls
 * back to each candidate's session-header `id` field for filenames whose stem isn't a bare id
 * (pi's own timestamp-prefixed filenames; legacy/synthetic sessions in oracle's own tests).
 * pie: session/mod.rs:191-225 (`find_session_path` + `find_path_by_id`). Deliberately uses only
 * a bounded header read per candidate (readSessionHeaderSync), not loadEntriesFromFile, so that a
 * mid-file-corruption throw (or a PORT-DIVERGENCE B8 salvage notice) only ever happens for the file
 * the caller actually resolves to and opens -- not for every other session merely being scanned
 * past during id lookup.
 */
export function findSessionPathById(dir: string, id: string): string | null {
	const files = listSessionFilesSortedSync(dir);
	for (const path of files) {
		const stem = basename(path, ".jsonl");
		if (stem === id || stem.startsWith(id)) return path;
		const header = readSessionHeaderSync(path);
		if (header && (header.id === id || header.id.startsWith(id))) return path;
	}
	return null;
}

/**
 * Resolve the session to resume: an explicit id/prefix, or (when omitted) the newest session in
 * `dir`. Returns the transcript *path* only -- callers open it via `SessionManager.open()`, which
 * is where PORT-DIVERGENCE B8's tail salvage (or a mid-file-corruption throw) applies, to the
 * chosen target alone.
 * pie: session/mod.rs:81-96 (`resume`).
 */
export function resolveResumeSessionPath(dir: string, explicitId?: string): string {
	const files = listSessionFilesSortedSync(dir);
	if (files.length === 0) {
		throw new Error(`no sessions to resume in ${dir}`);
	}
	if (explicitId) {
		const found = findSessionPathById(dir, explicitId);
		if (!found) {
			throw new Error(`no session matches id ${explicitId}`);
		}
		return found;
	}
	// listSessionFilesSortedSync sorts ascending, so the tail is newest (see the file header
	// comment above on filename sort order).
	return files[files.length - 1]!;
}

/** pie: session/mod.rs:227-231 (`newest_path`). */
export function newestSessionPath(dir: string): string | null {
	const files = listSessionFilesSortedSync(dir);
	return files.length > 0 ? files[files.length - 1]! : null;
}

/**
 * Delete a session by id (full uuidv7) or a unique prefix, along with its trigger/cron/endpoint
 * sidecars. Missing sidecars are not an error.
 * pie: session/mod.rs:164-189 (`delete_by_id`).
 */
export function deleteSessionById(dir: string, id: string): string {
	const path = findSessionPathById(dir, id);
	if (!path) {
		throw new Error(`no session matches id ${id}`);
	}
	unlinkSync(path);
	for (const sidecar of [triggerSidecarPath(path), cronSidecarPath(path), endpointSidecarPath(path)]) {
		try {
			unlinkSync(sidecar);
		} catch (error) {
			if ((error as NodeJS.ErrnoException)?.code !== "ENOENT") throw error;
		}
	}
	return path;
}

/**
 * Char-bounded preview truncation: JS strings already index by UTF-16 code unit, but
 * `Array.from` iterates by code point, matching oracle's `String::chars()` (byte-bounded
 * `String::truncate` would panic mid multi-byte character -- the oracle comment this mirrors).
 * pie: session/mod.rs:147-157 (tail of `first_user_text`).
 */
function truncateSessionPreview(rawText: string): string {
	const text = rawText.replace(/\n/g, " ");
	const chars = Array.from(text);
	if (chars.length > 80) {
		return `${chars.slice(0, 80).join("")}…`;
	}
	return text;
}

/**
 * Preview of the *first* user message, whatever its text turns out to be. Oracle returns
 * `Some(preview)` unconditionally once it reaches a user message -- an image-only (or otherwise
 * text-free) first turn yields an empty preview rather than falling through to the second user
 * message. Do not add a `if (!text) continue` skip here: that would silently promote a later
 * message into the listing.
 * pie: crates/coding-agent/src/session/mod.rs:130-158 (`first_user_text`).
 */
function firstUserPreview(entries: FileEntry[]): string | undefined {
	for (const entry of entries) {
		if (entry.type !== "message") continue;
		const message = (entry as SessionMessageEntry).message;
		if (!isMessageWithContent(message) || message.role !== "user") continue;
		return truncateSessionPreview(extractTextContent(message));
	}
	return undefined;
}

/** pie: session/mod.rs:11-18 (`SessionEntry`, the list-entry struct -- distinct from this file's
 * own `SessionEntry` union type, which models tree entries; renamed here to avoid the clash). */
export interface SessionListEntry {
	path: string;
	id: string;
	createdAt: string;
	preview: string | undefined;
	automation: AutomationCounts;
}

/**
 * List sessions for this cwd, oldest -> newest, with a short preview from the first user message
 * when available, and automation sidecar counts.
 *
 * A corrupted body line costs the *preview only*, never the whole listing. Oracle reaches the
 * same place by two separate steps: `repo.open(&path).await?` (session/mod.rs:101) parses the
 * header line and nothing else (jsonl_storage.rs:68-84), and the preview comes from
 * `first_user_text`, whose very first statement is `session.entries().await.ok()?`
 * (session/mod.rs:129) -- `.ok()?` swallows `load_entries`' `invalid entry: {e}` and yields
 * `None`. `pie --list-sessions` therefore works on a directory containing a truncated transcript
 * in both oracle and here, which is what parity scenario S8 asserts.
 *
 * PORT-DIVERGENCE B8 reaches this listing in one visible way: a session with a salvaged tail now
 * yields its preview instead of a blank one, because the healthy prefix parses. The scan stays
 * silent (`notify: false`) and never repairs -- it does not own these files, and one notice per
 * corrupted session would bury the listing it is printing.
 * pie: session/mod.rs:98-126 (`list_entries`) + :128-161 (`first_user_text`).
 */
export async function listSessionEntries(dir: string): Promise<SessionListEntry[]> {
	const files = await listSessionFilesSorted(dir);
	const out: SessionListEntry[] = [];
	for (const path of files) {
		// pie: session/mod.rs:101 `repo.open(&path).await?` -> jsonl_storage.rs:68-84, header only.
		const header = readSessionHeaderSync(path);
		let preview: string | undefined;
		try {
			preview = firstUserPreview(loadEntriesFromFile(path, { notify: false }));
		} catch {
			// pie: session/mod.rs:129 `session.entries().await.ok()?` -- mid-file corruption means no
			// preview, not a failed listing.
			preview = undefined;
		}
		out.push({
			path,
			id: header?.id ?? "?",
			createdAt: header?.timestamp ?? "?",
			preview,
			automation: await automationCounts(path),
		});
	}
	return out;
}

/**
 * Every session transcript in `dir`, oldest -> newest — the same ordering `listSessionEntries`
 * walks, without paying for its per-session preview parse and automation-sidecar reads.
 *
 * pie: commands.rs:2074-2077 (`FindCommand::run`'s `repo.list()`), which likewise takes the bare
 * path list and opens each session itself rather than going through `session::list_entries`.
 */
export async function listSessionTranscriptPaths(dir: string): Promise<string[]> {
	return await listSessionFilesSorted(dir);
}

/**
 * The text body of every user and assistant message in one session transcript, in file order.
 *
 * pie: commands.rs:2082-2104 — oracle keeps `AgentMessage::Llm(Message::User)` and
 * `AgentMessage::Llm(Message::Assistant)` and `continue`s past everything else (tool results,
 * custom entries, …). A user body is either the bare `UserContent::Text` string or its text blocks
 * joined with a single space; an assistant body is its text blocks joined the same way — which is
 * exactly what `extractTextContent` already does, so it is reused rather than re-derived.
 *
 * A transcript that fails to parse yields no text instead of throwing, matching oracle's
 * `session.entries().await.unwrap_or_default()` (commands.rs:2080): one corrupt session must not
 * abort a search across all of them.
 */
export function sessionMessageTexts(path: string): string[] {
	let entries: FileEntry[];
	try {
		entries = loadEntriesFromFile(path, { notify: false });
	} catch {
		return [];
	}
	const texts: string[] = [];
	for (const entry of entries) {
		if (entry.type !== "message") continue;
		const message = (entry as SessionMessageEntry).message;
		if (!isMessageWithContent(message)) continue;
		if (message.role !== "user" && message.role !== "assistant") continue;
		texts.push(extractTextContent(message));
	}
	return texts;
}

/**
 * When other sessions in this cwd's directory hold *enabled* automation, return a one-line hint
 * naming the newest such session so the user can resume it. `currentSessionPath` (the active
 * session's transcript path) is excluded from the scan.
 * pie: session/mod.rs:312-350 (`automation_elsewhere_hint`).
 */
export async function automationElsewhereHint(
	cwd: string,
	currentSessionPath?: string,
	sessionDir?: string,
): Promise<string | undefined> {
	// Same as listing sessions: this is a hint, and purely a read. The directory read is wrapped
	// in a try/catch, so a missing directory yields an empty list.
	const dir = sessionDir ?? sessionDirForCwd(cwd);
	const files = await listSessionFilesSorted(dir);
	const currentResolved = currentSessionPath ? resolve(currentSessionPath) : undefined;
	const holders: Array<{ path: string; counts: AutomationCounts }> = [];
	for (const path of files) {
		if (currentResolved && resolve(path) === currentResolved) continue;
		const counts = await automationCounts(path);
		if (automationCountsAnyEnabled(counts)) holders.push({ path, counts });
	}
	if (holders.length === 0) return undefined;
	const extra = holders.length - 1;
	// listSessionFilesSorted sorts ascending, so the last holder is the newest.
	const { path, counts } = holders[holders.length - 1]!;
	const header = readSessionHeaderSync(path);
	const shortId = (header?.id ?? "").slice(0, 16);
	const badge = automationCountsBadge(counts) ?? "";
	const more = extra > 0 ? ` (+${extra} more session(s))` : "";
	return `automation is session-scoped: session ${shortId} has ${badge} enabled${more}; resume it with \`pie --resume-id ${shortId}\``;
}
