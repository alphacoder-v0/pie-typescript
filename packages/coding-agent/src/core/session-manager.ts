/**
 * On-disk shape of a transcript's first line.
 *
 * pie: crates/agent/src/harness/session/session.rs:194-219 (`SessionMetadata` +
 * `JsonlSessionMetadata`), written by jsonl_storage.rs:46-60 (`JsonlSessionStorage::create`) and
 * read back by :69-87 (`open`). Oracle's header is the serialized metadata struct and nothing
 * else: `{id, createdAt, cwd, path, parentSessionPath?, importedFrom?}`. Two consequences that
 * pi's own header shape (`{type:"session", version, id, timestamp, cwd, parentSession?}`) does
 * not share:
 *
 *   - **no `type` tag** — line *position* identifies the header (`open` takes `lines.next()`,
 *     `load_entries` skips exactly one line), so a `type` discriminator would be redundant;
 *   - **no `version`** — oracle has no on-disk schema versioning at all;
 *   - **a `path` field** — the transcript records its own absolute path. Oracle reads it back for
 *     the automation sidecars (`session/mod.rs` `trigger_sidecar_path_for_session` /
 *     `cron_sidecar_path_for_session`) and for `.piesession` manifests
 *     (`session_archive.rs` `manifest.source.session_path`); phase 12's UNSURE #1/#5 recorded both
 *     as unportable precisely because pi's header had no such field.
 *
 * This matters beyond the differ: phase 9/12 put both binaries on the same `~/.pie/sessions/`
 * tree, so a user coming from Rust pie hands TS pie oracle-shaped transcripts. Keeping pi's header
 * would have made every one of them parse as "no header" and vanish from `--list-sessions` /
 * `--resume` (`loadEntriesFromFile` returns `[]`).
 *
 * The in-memory `SessionHeader` is deliberately left alone — `fileEntries[0]` keeps its
 * `type:"session"`/`version` so the ~30 `entry.type === "session"` call sites, the v1→v3
 * migrations and `session-archive.ts` all keep working. Only the file boundary changes.
 */
interface WireSessionHeader {
	id: string;
	createdAt: string;
	cwd: string;
	path: string;
	parentSessionPath?: string;
	importedFrom?: SessionImportOrigin;
}

/**
 * Render a header for the file. `path` is the transcript's own absolute path (oracle:
 * `path.to_string_lossy()` at jsonl_storage.rs:52).
 */
export function serializeSessionHeader(header: SessionHeader, path: string): string {
	const wire: WireSessionHeader = {
		id: header.id,
		createdAt: header.timestamp,
		cwd: header.cwd,
		path,
	};
	// serde's `skip_serializing_if = "Option::is_none"` on both optional fields
	// (session.rs:207-219): absent, not null.
	if (header.parentSession !== undefined) wire.parentSessionPath = header.parentSession;
	if (header.importedFrom !== undefined) wire.importedFrom = header.importedFrom;
	return JSON.stringify(wire);
}

/** `JSON.stringify` for one file line: headers take the oracle wire shape, entries are verbatim. */
function serializeFileEntry(entry: FileEntry, path: string): string {
	return entry.type === "session" ? serializeSessionHeader(entry as SessionHeader, path) : JSON.stringify(entry);
}

/**
 * Parse a already-JSON-parsed first line into the in-memory `SessionHeader`, or `null` when it
 * is not a header at all.
 *
 * Accepts two shapes:
 *   1. oracle's (`WireSessionHeader`) — what this build writes;
 *   2. pi's legacy `{type:"session", version?, ...}` — read-only. Oracle would reject these
 *      (serde needs `createdAt`/`path`), so this is a deliberate read-side superset, kept for the
 *      same reason ED14 schedules one for auth.json: transcripts written by an earlier build of
 *      *this* binary live at the shared path too, and silently dropping them would lose history.
 *      It is also what keeps the v1→v2→v3 migrations (and their tests) reachable — those are
 *      keyed on the legacy `version` field, which the oracle shape does not carry.
 */
export function parseSessionHeader(parsed: unknown): SessionHeader | null {
	if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) return null;
	const raw = parsed as Record<string, unknown>;
	if (typeof raw.id !== "string" || !raw.id) return null;

	if (raw.type === "session") {
		return raw as unknown as SessionHeader;
	}
	if (typeof raw.createdAt !== "string" || typeof raw.cwd !== "string") return null;
	const header: SessionHeader = {
		type: "session",
		version: CURRENT_SESSION_VERSION,
		id: raw.id,
		timestamp: raw.createdAt,
		cwd: raw.cwd,
	};
	if (typeof raw.parentSessionPath === "string") header.parentSession = raw.parentSessionPath;
	if (raw.importedFrom !== undefined) header.importedFrom = raw.importedFrom as SessionImportOrigin;
	return header;
}

/** Parse + validate a raw first line. Returns `null` for anything that is not a session header. */
export function parseSessionHeaderLine(line: string): SessionHeader | null {
	try {
		return parseSessionHeader(JSON.parse(line));
	} catch {
		return null;
	}
}

